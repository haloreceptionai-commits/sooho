"""Documentary soundtrack: directed narration (planned pauses), a different music bed per chapter that ducks under the voice, hush before
reveals, risers and hits on the beats that ask for them, optional ambience, and a measured two-pass loudness target.

The narration is never stretched or filtered: only silence is added at word boundaries. Everything else is generated by sound_lib
(numpy-synthesised, no downloads), so a render is deterministic and works offline.
"""
import json
import os
import re
import subprocess
import sys
import wave
from concurrent.futures import ProcessPoolExecutor

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import sound_lib as lib  # noqa: E402

RATE = 48000
BED_SEC = 80
FFMPEG = os.environ.get('FFMPEG') or 'ffmpeg'
TARGET_LUFS = -15.0


def read_wav(path):
    with wave.open(str(path), 'rb') as f:
        if f.getsampwidth() != 2:
            raise ValueError('Expected 16-bit narration')
        if f.getframerate() != RATE:
            raise ValueError('Narration must be 48 kHz (the worker converts it first)')
        data = np.frombuffer(f.readframes(f.getnframes()), dtype='<i2').astype(np.float32) / 32768.0
        return data.reshape(-1, f.getnchannels()).mean(axis=1)


def write_wav(path, x, channels=2):
    x = np.clip(x, -1, 1)
    pcm = (x * 32767).astype('<i2')
    if channels == 2:
        pcm = np.repeat(pcm[:, None], 2, axis=1).reshape(-1)
    with wave.open(str(path), 'wb') as f:
        f.setnchannels(channels)
        f.setsampwidth(2)
        f.setframerate(RATE)
        f.writeframes(pcm.tobytes())


def assemble_voice(takes, edits, duration):
    """Joins the recorded takes following the timeline's edit list (silence at planned pauses); the result is exactly `duration` long."""
    parts = []
    fade = int(.006 * RATE)
    for e in edits:
        if e[0] == 'silence':
            parts.append(np.zeros(int(round(e[1] * RATE)), np.float32))
        else:
            _, k, a, b = e
            seg = takes[k][int(round(a * RATE)):int(round(b * RATE))].copy()
            if len(seg) > 2 * fade:
                seg[:fade] *= np.linspace(0, 1, fade)
                seg[-fade:] *= np.linspace(1, 0, fade)
            parts.append(seg)
    v = np.concatenate(parts) if parts else np.zeros(0, np.float32)
    n = int(round(duration * RATE))
    return v[:n] if len(v) >= n else np.pad(v, (0, n - len(v)))


def gated_rms(x, win=.4, floor=1e-3):
    w = int(win * RATE)
    n = len(x) // w
    if n == 0:
        return float(np.sqrt(np.mean(x ** 2))) if len(x) else 0.0
    p = (x[:n * w].reshape(n, w) ** 2).mean(axis=1)
    p = p[p > floor ** 2]
    return float(np.sqrt(p.mean())) if len(p) else 0.0


def _bed(mood_seed):
    mood, seed = mood_seed
    return mood, lib.music_bed(mood, BED_SEC * RATE, 0, seed)


def make_beds(moods, workers=3):
    moods = sorted(set(moods))
    if len(moods) > 1 and workers > 1:
        try:
            with ProcessPoolExecutor(max_workers=min(workers, len(moods))) as ex:
                return dict(ex.map(_bed, [(m, 11 + i) for i, m in enumerate(moods)]))
        except Exception as e:   # a pool that cannot start (or dies) never stops the render: make the beds one after another
            print('parallel music failed, making beds one at a time:', type(e).__name__)
    return dict(_bed((m, 11 + i)) for i, m in enumerate(moods))


def section_audio(bed, length, index):
    """`length` seconds of one mood, starting at a different place of the bed for each section, looped with a crossfade if it must be longer."""
    n = int(length * RATE)
    if n <= len(bed) - 2 * RATE:
        off = int((index * 13.7 * RATE) % max(1, len(bed) - n))
        return bed[off:off + n].copy()
    out = np.zeros(n, np.float32)
    x = int(2.5 * RATE)
    pos, k = 0, 0
    while pos < n:
        seg = bed[(k * 7 * RATE) % max(1, len(bed) // 2):][:len(bed) // 2 + x]
        m = min(len(seg), n - pos)
        piece = seg[:m].copy()
        if k:
            c = min(x, m)
            piece[:c] *= np.linspace(0, 1, c)
            out[pos:pos + c] *= np.linspace(1, 0, c)
        out[pos:pos + m] += piece
        pos += max(1, m - x)
        k += 1
    return out


def music_sections(manifest, timeline, default_mood):
    scenes = manifest['scenes']
    first_start = {}
    for b in timeline['beats']:
        first_start.setdefault(b['scene'], b['start'])
    plan = sorted([m for m in (manifest.get('music') or []) if isinstance(m.get('scene'), int) and m.get('mood') in lib.MOODS and 0 <= m['scene'] < len(scenes)], key=lambda m: m['scene'])
    if not plan or plan[0]['scene'] != 0:
        plan = [{'scene': 0, 'mood': default_mood}] + plan
    out = []
    for i, m in enumerate(plan):
        start = 0.0 if i == 0 else first_start.get(m['scene'], 0.0)
        end = timeline['duration'] if i + 1 == len(plan) else first_start.get(plan[i + 1]['scene'], timeline['duration'])
        if end - start > .5:
            out.append((start, end, m['mood']))
    return out


def voice_envelope(voice):
    """1.0 where the narrator is quiet, `duck` where speaking; 20 ms blocks, quick to duck, slow to come back."""
    blk = int(.02 * RATE)
    n = len(voice) // blk
    rms = np.sqrt((voice[:n * blk].reshape(n, blk) ** 2).mean(axis=1))
    ref = gated_rms(voice) or 1e-3
    active = rms > ref * .22
    env = np.empty(n, np.float32)
    level = 1.0
    for i in range(n):
        target = .36 if active[i] else 1.0
        level += (.5 if target < level else .035) * (target - level)
        env[i] = level
    full = np.interp(np.arange(len(voice)), (np.arange(n) + .5) * blk, env).astype(np.float32)
    return full


def place(buf, start_sec, snd, gain):
    i = int(round(start_sec * RATE))
    if i >= len(buf) or len(snd) == 0:
        return
    if i < 0:
        snd = snd[-i:]
        i = 0
    m = min(len(snd), len(buf) - i)
    buf[i:i + m] += snd[:m] * gain


def sfx_events(manifest, timeline):
    """(time, kind, gain) for every sound the beats ask for, plus whoosh on whip cuts and a soft hit under chapter cards."""
    ev = []
    beats = timeline['beats']
    for i, b in enumerate(beats):
        kind = b.get('sfx')
        if not kind or kind == 'none':
            kind = 'whoosh' if b.get('transition') == 'whip' else None
        v = b['visual']
        if kind == 'riser':
            ev.append((b['start'], 'riser', 1.0))
        elif kind == 'hit':
            ev.append((b['start'], 'impact', 1.0))
        elif kind == 'sting':
            ev.append((b['start'], 'reveal', 1.0))
        elif kind == 'whoosh':
            ev.append((max(0.0, b['start'] - .08), 'whoosh', .8))
        elif kind in ('scratch', 'boing'):   # comic timing for a wry aside
            ev.append((b['start'] + .05, kind, .7))
        for o in b.get('overlays') or []:
            if o.get('kind') == 'chapter':
                ev.append((b['start'] + float(o.get('at', 0)), 'whoosh', .7))
                ev.append((b['start'] + float(o.get('at', 0)) + .15, 'impact', .45))
        if v['type'] == 'card' and v['card'] == 'number' and i > 0:
            ev.append((b['start'] + 1.35, 'impact', .35))   # the counter lands
    return ev


def build(manifest, timeline, voice_takes, default_mood='suspense', workers=3):
    """Returns (mono mix as float32, report). Levels are relative to the narration; loudness is finished by loudnorm()."""
    duration = timeline['duration']
    n = int(round(duration * RATE))
    voice = assemble_voice(voice_takes, timeline['edits'], duration)
    vr = gated_rms(voice)
    if vr <= 0:
        raise ValueError('Narration is silent')
    sections = music_sections(manifest, timeline, default_mood)
    beds = make_beds([m for _, _, m in sections], workers)
    music = np.zeros(n, np.float32)
    for k, (a, b, mood) in enumerate(sections):
        pad = 0 if k == 0 else int(.9 * RATE)
        s0, s1 = int(a * RATE) - pad // 2, min(n, int(b * RATE) + (int(.9 * RATE) // 2 if k + 1 < len(sections) else 0))
        s0 = max(0, s0)
        seg = section_audio(beds[mood], (s1 - s0) / RATE, k)[:s1 - s0]
        if k and len(seg) > pad:
            seg[:pad] *= np.linspace(0, 1, pad)
        if k + 1 < len(sections) and len(seg) > .9 * RATE:
            c = int(.9 * RATE)
            seg[-c:] *= np.linspace(1, 0, c)
        music[s0:s0 + len(seg)] += seg
    # hush: the music falls away just before a planned pause and the answer lands in near silence
    env = voice_envelope(voice)
    shift_total = 0.0
    for p in manifest.get('pauses') or []:
        if p.get('hush') and isinstance(p.get('scene'), int):
            ws = [w for w in timeline['words'] if w['scene'] == p['scene'] and w['wi'] == p['after_word']]
            if ws:
                t1 = ws[0]['t1']
                a, b = max(0, int((t1 - .5) * RATE)), min(n, int((t1 + float(p['sec']) + .1) * RATE))
                ramp = int(.5 * RATE)
                env[a:b] = np.minimum(env[a:b], .06)
                env[max(0, a - ramp):a] = np.minimum(env[max(0, a - ramp):a], np.linspace(1, .06, a - max(0, a - ramp)))
    mr = gated_rms(music)
    music_gain = (.30 * vr / mr) if mr else 0.0
    mix = voice + music * env * music_gain
    # one-shot sounds
    sfx = np.zeros(n, np.float32)
    for t, kind, g in sfx_events(manifest, timeline):
        if kind == 'riser':
            dur = 2.0
            snd = lib._riser(dur, 5)
            place(sfx, t - dur, snd, .55 * g)
        else:
            snd = lib.render(kind, 3)
            place(sfx, t, snd, g)
    peak = float(np.abs(sfx).max()) or 1.0
    vp = float(np.abs(voice).max()) or 1.0
    mix = mix + sfx * (.55 * vp / peak)
    # ambience under scenes that name one
    amb = np.zeros(n, np.float32)
    first = {}
    for b in timeline['beats']:
        first.setdefault(b['scene'], b['start'])
    scene_ids = sorted(first)
    for si in scene_ids:
        kind = manifest['scenes'][si].get('ambience')
        if kind in lib.AMBIENT:
            a = first[si]
            nxt = [first[x] for x in scene_ids if x > si]
            e = nxt[0] if nxt else duration
            snd = lib.ambience(kind, int((e - a) * RATE) + 1, 7 + si)[:int((e - a) * RATE)]
            f = min(len(snd) // 2, int(.6 * RATE))
            if f:
                snd = snd.copy(); snd[:f] *= np.linspace(0, 1, f); snd[-f:] *= np.linspace(1, 0, f)
            place(amb, a, snd, 1.0)
    ar = gated_rms(amb)
    if ar:
        mix = mix + amb * (.10 * vr / ar)
    peak = float(np.abs(mix).max())
    if peak > .95:
        mix = mix * (.95 / peak)
    report = {'voice_rms': vr, 'music_gain': music_gain, 'sections': [(round(a, 2), round(b, 2), m) for a, b, m in sections], 'sfx': len(sfx_events(manifest, timeline)), 'samples': n}
    return mix.astype(np.float32), report


def loudnorm(src, dst, target=TARGET_LUFS):
    """Two-pass EBU R128: measure, then apply a linear gain so quiet and loud videos land at the same level. Returns the measured input stats."""
    p1 = subprocess.run([FFMPEG, '-hide_banner', '-nostats', '-i', src, '-af', f'loudnorm=I={target}:TP=-1.5:LRA=11:print_format=json', '-f', 'null', '-'], capture_output=True)
    text = p1.stderr.decode(errors='replace')
    m = re.search(r'\{[^{}]*"input_i"[^{}]*\}', text, re.S)
    if p1.returncode != 0 or not m:
        raise RuntimeError('Loudness measurement failed: ' + text[-300:])
    st = json.loads(m.group(0))
    af = (f'loudnorm=I={target}:TP=-1.5:LRA=11:measured_I={st["input_i"]}:measured_TP={st["input_tp"]}:measured_LRA={st["input_lra"]}:'
          f'measured_thresh={st["input_thresh"]}:offset={st["target_offset"]}:linear=true')
    p2 = subprocess.run([FFMPEG, '-y', '-hide_banner', '-loglevel', 'error', '-i', src, '-af', af, '-ar', str(RATE), '-ac', '2', '-c:a', 'pcm_s16le', dst], capture_output=True)
    if p2.returncode != 0:
        raise RuntimeError('Loudness pass failed: ' + p2.stderr.decode(errors='replace')[-300:])
    return {'lufs': float(st['input_i']), 'lra': float(st['input_lra']), 'tp': float(st['input_tp'])}
